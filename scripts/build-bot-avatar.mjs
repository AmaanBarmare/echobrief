#!/usr/bin/env node
/**
 * Builds the image the Recall bot shows as its camera feed once it is admitted
 * to a meeting, and writes it out as the base64 constant the bot-create payloads
 * send in `automatic_video_output`.
 *
 * Recall's constraints: jpeg, 16:9, at most 1280x720, at most 1.3 MB. We render
 * at 2x and downscale so the mark stays clean on platforms that letterbox.
 *
 * Run with: npm run brand:avatar
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const LOCKUP = join(ROOT, 'brand/logo/png/echobrief-lockup-dark.png')
const OUT_JPEG = join(ROOT, 'brand/logo/png/echobrief-bot-avatar-1280x720.jpg')
const OUT_TS = join(ROOT, 'supabase/functions/_shared/bot-avatar.ts')

const CHAR = '#120C09' // neutrals.dark.char — the app's own background

const tmp = mkdtempSync(join(tmpdir(), 'eb-avatar-'))
const big = join(tmp, 'big.png')

// 2560x1440 canvas, lockup at 64% of the width, centred.
execFileSync('magick', [
  '-size', '2560x1440', `xc:${CHAR}`,
  '(', LOCKUP, '-resize', '1650x', ')',
  '-gravity', 'center', '-composite',
  big,
])

execFileSync('magick', [
  big,
  '-resize', '1280x720',
  '-quality', '92',
  '-sampling-factor', '4:4:4',
  '-strip',
  OUT_JPEG,
])

const bytes = readFileSync(OUT_JPEG)
if (bytes.length > 1_300_000) {
  throw new Error(`avatar is ${bytes.length} bytes, over Recall's 1.3 MB ceiling`)
}
const b64 = bytes.toString('base64')

writeFileSync(OUT_TS, `// GENERATED by scripts/build-bot-avatar.mjs — do not edit by hand.
// The EchoBrief lockup on char, 1280x720 jpeg, ${bytes.length} bytes.
// Sent as \`automatic_video_output\` on bot create so the notetaker shows the
// brand mark as its camera feed instead of a blank tile once it is admitted.
// Regenerate with: npm run brand:avatar
export const BOT_AVATAR_JPEG_B64 =
  "${b64}";

export const BOT_AVATAR_OUTPUT = {
  in_call_recording: { kind: "jpeg", b64_data: BOT_AVATAR_JPEG_B64 },
} as const;
`)

console.log(`bot avatar: ${OUT_JPEG} (${(bytes.length / 1024).toFixed(0)} KB) -> ${OUT_TS}`)
